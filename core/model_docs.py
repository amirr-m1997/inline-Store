def help_for_path(path: str) -> str:
    """راهنمای یک نشانی سایدبار: اول مدل، بعد صفحه‌ی سفارشی."""
    import re

    match = re.match(r"^/admin/(\w+)/(\w+)/?$", path or "")
    if match:
        text = help_for(match.group(1), match.group(2))
        if text:
            return text
    return PAGE_HELP.get(path or "", "")


def help_for(app_label: str, model_name: str) -> str:
    """توضیح مدل؛ رشتهٔ خالی اگر توضیحی ثبت نشده باشد."""
    return MODEL_HELP.get(f"{app_label}.{model_name}", "")


def short_help(app_label: str, model_name: str, limit: int = 70) -> str:
    """نسخهٔ کوتاه توضیح (برای tooltip سایدبار)."""
    text = help_for(app_label, model_name)
    if len(text) <= limit:
        return text
    return text[: limit - 1].rsplit(" ", 1)[0] + "…"
